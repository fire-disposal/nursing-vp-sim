def extract_keywords(text: str) -> dict:
    """从文本中提取医学关键词（精确匹配 + jieba 分词）"""
    text = str(text)
    return {
        "diseases": [k for k in DISEASE_KEYWORDS if k in text],
        "diagnoses": [k for k in NURSING_DIAGNOSIS_KEYWORDS if k in text],
        "symptoms": [k for k in SYMPTOM_KEYWORDS if k in text],
        "measures": [k for k in NURSING_MEASURE_KEYWORDS if k in text],
    }


def tokenize(text: str) -> list[str]:
    """jieba 分词并去重，优先保留医学关键词"""
    words = jieba.lcut(text)
    result = []
    seen = set()
    for w in words:
        w = w.strip()
        if len(w) < 2 or w in seen:
            continue
        seen.add(w)
        result.append(w)
    return result
